def nikhilam_divide_by_9(n: int):
    """Division by 9: running sums of digits give quotient digits."""
    d = [int(c) for c in str(n)]
    running = []
    s = 0
    for x in d[:-1]:
        s += x
        running.append(s)
    rem = s + d[-1]
    # Convert running column sums into a number (handles carries)
    q = 0
    for r in running:
        q = q * 10 + r
    q += rem // 9
    rem %= 9
    steps = [f"Running digit sums (quotient columns): {', '.join(map(str, running)) or '0'}", f"Last running sum + last digit = remainder column {s + d[-1]}", f"Adjust carries/remainder ≥ 9 → quotient {fmt(q)}, remainder {rem}"]
    return (q, rem), steps


def nikhilam_divide(n: int, divisor: int):
    """Nikhilam division for divisors just below a power of ten (e.g. 8, 88, 97, 997)."""
    k = len(str(divisor))
    base = 10 ** k
    comp = base - divisor
    assert 0 < comp < base
    comp_digits = [int(c) for c in str(comp).zfill(k)]
    dd = [int(c) for c in str(n)]
    if len(dd) <= k:
        q, r = divmod(n, divisor)
        return (q, r), [f"Dividend has no more digits than the divisor: compare directly → quotient {q}, remainder {r}"]
    cols = dd[:]
    qlen = len(dd) - k
    for i in range(qlen):
        for j, c in enumerate(comp_digits):
            cols[i + 1 + j] += cols[i] * c
    qcols = cols[:qlen]
    rcols = cols[qlen:]
    q = 0
    for x in qcols:
        q = q * 10 + x
    r = 0
    for x in rcols:
        r = r * 10 + x
    q += r // divisor
    r %= divisor
    steps = [
        f"Divisor {divisor} = {fmt(base)} {MINUS} {comp}; write complement digits {''.join(map(str, comp_digits))}",
        f"Split dividend: {''.join(map(str, dd[:qlen]))} | {''.join(map(str, dd[qlen:]))}",
        f"Column totals after multiplying by the complement: {qcols} | {rcols}",
        f"Resolve carries and remainder → quotient {fmt(q)}, remainder {r}",
    ]
    return (q, r), steps


def paravartya_divide(n: int, divisor: int):
    """Paravartya Yojayet: divisor slightly above a power of ten (e.g. 12, 112, 1013)."""
    k = len(str(divisor)) - 1
    base = 10 ** k
    excess = divisor - base
    assert 0 < excess < base
    flags = [-int(c) for c in str(excess).zfill(k)]
    dd = [int(c) for c in str(n)]
    if len(dd) <= k:
        q, r = divmod(n, divisor)
        return (q, r), [f"Dividend has fewer digits than the divisor: quotient {q}, remainder {r}"]
    cols = dd[:]
    qlen = len(dd) - k
    for i in range(qlen):
        for j, f in enumerate(flags):
            cols[i + 1 + j] += cols[i] * f
    q = 0
    for x in cols[:qlen]:
        q = q * 10 + x
    r = 0
    for x in cols[qlen:]:
        r = r * 10 + x
    while r < 0:
        q -= 1
        r += divisor
    q += r // divisor
    r %= divisor
    steps = [
        f"Divisor {divisor} = {fmt(base)} + {excess}; transposed flags: {', '.join(f'{MINUS}{abs(f)}' for f in flags)}",
        f"Column values after applying flags: {cols[:qlen]} | {cols[qlen:]}",
        f"Resolve negatives/carries → quotient {fmt(q)}, remainder {r}",
    ]
    return (q, r), steps


def recurring_1_over_x9(den: int, length: int | None = None):
    """Ekadhikena Purvena for 1/19, 1/29, ...: multiply from the right by (one more)."""
    assert den % 10 == 9
    ek = den // 10 + 1
    period = 1
    while pow(10, period, den) != 1:
        period += 1
    length = length or period
    digits = []
    carry = 0
    cur = 1
    for _ in range(length):
        digits.append(cur % 10)
        total = cur * ek + carry
        carry, cur = divmod(total, 10)
        cur = total % 10
        carry = total // 10
    s = "".join(map(str, digits[::-1]))
    return s, [f"Ekadhika (one more than {den // 10}) = {ek}", f"Start with 1 on the right; repeatedly multiply by {ek}, write the unit digit, carry the rest", f"Recurring block ({period} digits): {s}"]


def shesanyankena(den: int):
    """Remainders × last digit (mod 10) gives the decimal of 1/den for den ending in 7 or 3."""
    rems = []
    r = 1
    while True:
        r = (r * 10) % den
        rems.append(r)
        if r == 1:
            break
    last = den % 10
    digits = "".join(str((x * last) % 10) for x in rems)
    return digits, [f"Remainders of 10, 100, 1000 … ÷ {den}: {', '.join(map(str, rems))}", f"Multiply each remainder by the last digit {last}, keep units", f"1/{den} = 0.({digits}) recurring"]


def vinculum(n: int) -> str:
    """Rewrite digits greater than 5 using bar (negative) digits. Returns e.g. '1 1̄ 2'."""
    d = [int(c) for c in str(n)][::-1]
    out = []
    carry = 0
    for x in d:
        x += carry
        if x > 5:
            out.append(-(10 - x))
            carry = 1
        else:
            out.append(x)
            carry = 0
    if carry:
        out.append(carry)
    return " ".join(f"{abs(x)}\u0305" if x < 0 else str(x) for x in out[::-1])


def vinculum_value(n: int) -> int:
    d = [int(c) for c in str(n)][::-1]
    total = 0
    carry = 0
    for i, x in enumerate(d):
        x += carry
        if x > 5:
            total += -(10 - x) * 10 ** i
            carry = 1
        else:
            total += x * 10 ** i
            carry = 0
    total += carry * 10 ** len(d)
    return total
