"""Vedic calculation algorithms with step-by-step traces.

Every function returns the numeric result and a list of human-readable steps.
The test-suite checks each algorithm against ordinary Python arithmetic, so the
worked solutions printed in the book are generated by code that is verified.
"""
from __future__ import annotations

from fractions import Fraction

MINUS = "\u2212"


def fmt(n) -> str:
    """Format a number with Indian digit grouping and a true minus sign."""
    if isinstance(n, Fraction):
        if n.denominator == 1:
            return fmt(n.numerator)
        return f"{fmt(n.numerator)}/{n.denominator}"
    if isinstance(n, float):
        if n == int(n):
            return fmt(int(n))
        s = f"{n:.6f}".rstrip("0").rstrip(".")
        whole, _, frac = s.partition(".")
        sign = MINUS if whole.startswith("-") else ""
        whole = whole.lstrip("-")
        return sign + fmt(int(whole)).lstrip(MINUS) + ("." + frac if frac else "")
    sign = MINUS if n < 0 else ""
    s = str(abs(int(n)))
    if len(s) <= 3:
        return sign + s
    head, tail = s[:-3], s[-3:]
    groups = []
    while len(head) > 2:
        groups.insert(0, head[-2:])
        head = head[:-2]
    if head:
        groups.insert(0, head)
    return sign + ",".join(groups + [tail])


def fmt_intl(n: int) -> str:
    sign = MINUS if n < 0 else ""
    return sign + f"{abs(n):,}"


def digit_sum_root(n: int) -> int:
    """Beejank / digital root (casting out nines)."""
    n = abs(n)
    return 0 if n == 0 else 1 + (n - 1) % 9


