def nikhilam_multiply(a: int, b: int, base: int | None = None):
    """Nikhilam: multiply numbers near a power-of-ten base (or a multiple of one).

    base may be 10**k or m*10**k (working base). Returns (product, steps).
    """
    if base is None:
        k = max(len(str(a)), len(str(b)))
        candidates = [10 ** (k - 1), 10 ** k]
        base = min(candidates, key=lambda c: abs(a - c) + abs(b - c))
    # Split working base into multiplier * power of ten
    p = 10 ** (len(str(base)) - 1)
    mult = base // p
    if mult * p != base:
        raise ValueError("base must be m * 10**k")
    da, db = a - base, b - base
    left = (a + db) * mult
    right = da * db
    digits = len(str(p)) - 1
    product = left * p + right
    sa = lambda d: f"+{d}" if d >= 0 else f"{MINUS}{abs(d)}"
    steps = [
        f"Base = {fmt(base)}" + (f" (working base {mult} × {fmt(p)})" if mult > 1 else ""),
        f"Deviations: {a} → {sa(da)},  {b} → {sa(db)}",
        f"Left part (cross): {a} {'+' if db >= 0 else MINUS} {abs(db)} = {a + db}" + (f", then × {mult} = {left}" if mult > 1 else ""),
        f"Right part: ({sa(da)}) × ({sa(db)}) = {sa(right) if right < 0 else right}",
    ]
    if digits > 0:
        if right < 0:
            steps.append(f"Right part is negative: borrow 1 from left → {left} × {fmt(p)} {MINUS} {abs(right)}")
        elif right >= p:
            steps.append(f"Right part has more than {digits} digit(s): carry {right // p} to the left")
        else:
            steps.append(f"Right part padded to {digits} digit(s): {str(right).zfill(digits)}")
    steps.append(f"Answer = {fmt(product)}")
    return product, steps


def urdhva_multiply(a: int, b: int):
    """Urdhva-Tiryagbhyam (vertically and crosswise) for any digit lengths."""
    da = [int(c) for c in str(a)][::-1]
    db = [int(c) for c in str(b)][::-1]
    n = max(len(da), len(db))
    da += [0] * (n - len(da))
    db += [0] * (n - len(db))
    cols = []
    for k in range(2 * n - 1):
        terms = [(da[i], db[k - i]) for i in range(n) if 0 <= k - i < n]
        cols.append((terms, sum(x * y for x, y in terms)))
    steps = []
    carry = 0
    out = []
    for idx, (terms, s) in enumerate(cols):
        expr = " + ".join(f"{x}×{y}" for x, y in terms)
        total = s + carry
        digit, new_carry = total % 10, total // 10
        steps.append(f"Column {idx + 1} (from right): {expr} = {s}" + (f", + carry {carry} = {total}" if carry else "") + f" → write {digit}, carry {new_carry}")
        out.append(digit)
        carry = new_carry
    while carry:
        out.append(carry % 10)
        carry //= 10
    product = int("".join(map(str, out[::-1])))
    steps.append(f"Answer = {fmt(product)}")
    return product, steps


def square_ending_5(n: int):
    """Ekadhikena Purvena: (10a + 5)² = a(a+1) | 25."""
    assert n % 10 == 5
    a = n // 10
    left = a * (a + 1)
    result = left * 100 + 25
    steps = [f"Digits before 5: {a}", f"{a} × (one more = {a + 1}) = {left}", f"Attach 25 → {fmt(result)}"]
    return result, steps


def same_prefix_units_ten(a: int, b: int):
    """Antyayordasake'pi: same leading part, last digits add to 10."""
    pa, pb = a // 10, b // 10
    ua, ub = a % 10, b % 10
    assert pa == pb and ua + ub == 10
    left = pa * (pa + 1)
    right = ua * ub
    result = left * 100 + right
    steps = [
        f"Same leading part {pa}; last digits {ua} + {ub} = 10 ✓",
        f"Left: {pa} × {pa + 1} = {left}",
        f"Right: {ua} × {ub} = {right:02d} (always two digits)",
        f"Answer = {fmt(result)}",
    ]
    return result, steps


def yavadunam_square(n: int, base: int | None = None):
    """Square near a base: (base ± d)² = (n ± d) | d², right part has base-digits."""
    if base is None:
        base = 10 ** (len(str(n)) - 1)
        if abs(n - 10 * base) < abs(n - base):
            base *= 10
    d = n - base
    digits = len(str(base)) - 1
    left = n + d
    right = d * d
    result = left * base + right
    sign = "+" if d >= 0 else MINUS
    steps = [
        f"Base {fmt(base)}, deviation {sign}{abs(d)}",
        f"Left: {n} {sign} {abs(d)} = {left}",
        f"Right: {abs(d)}² = {right} (needs {digits} digit(s)" + (f", carry {right // base}" if right >= base else "") + ")",
        f"Answer = {fmt(result)}",
    ]
    return result, steps


def square_near_50(n: int):
    """(50 + d)² = (25 + d) hundreds + d²."""
    d = n - 50
    left = 25 + d
    right = d * d
    result = left * 100 + right
    sign = "+" if d >= 0 else MINUS
    steps = [f"Deviation from 50: {sign}{abs(d)}", f"Left: 25 {sign} {abs(d)} = {left}", f"Right: {abs(d)}² = {right:02d}", f"Answer = {fmt(result)}"]
    return result, steps


def duplex(digits: list[int]) -> int:
    n = len(digits)
    total = 0
    for i in range(n // 2):
        total += 2 * digits[i] * digits[n - 1 - i]
    if n % 2:
        total += digits[n // 2] ** 2
    return total


def duplex_square(n: int):
    """Dwandwa-yoga (duplex) squaring for any number."""
    d = [int(c) for c in str(n)]
    L = len(d)
    cols = []
    for k in range(2 * L - 1):
        lo, hi = max(0, k - L + 1), min(k, L - 1)
        cols.append(duplex(d[lo:hi + 1]))
    steps = [f"Duplexes from left: {', '.join(map(str, cols))}"]
    value = 0
    for c in cols:
        value = value * 10 + c
    steps.append(f"Combine with carries (right to left) → {fmt(value)}")
    return value, steps


def times_11(n: int):
    d = [int(c) for c in str(n)]
    pairs = [d[i] + d[i + 1] for i in range(len(d) - 1)]
    result = n * 11
    steps = [f"Write first digit {d[0]} and last digit {d[-1]}", f"In between, add neighbours: {', '.join(f'{d[i]}+{d[i+1]}={p}' for i, p in enumerate(pairs))}", "Carry where a sum ≥ 10", f"Answer = {fmt(result)}"]
    return result, steps


def ekanyunena(n: int, nines: int):
    """Ekanyunena Purvena: n × 99..9 where n has at most as many digits as the nines."""
    m = 10 ** nines - 1
    assert 0 < n <= m
    left = n - 1
    right = m - left
    result = left * 10 ** nines + right
    steps = [f"Left: {n} {MINUS} 1 = {left}", f"Right: {fmt(m)} {MINUS} {left} = {str(right).zfill(nines)}", f"Answer = {fmt(result)}"]
    return result, steps


